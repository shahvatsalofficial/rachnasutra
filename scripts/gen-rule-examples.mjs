// Generates documents/rachnasutra/15-rule-examples.md by actually running the audit on each case in fixtures/rule-cases.mjs.
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { runAudit } from '../dist/audit.js';
import { RULE_CATALOG } from '../dist/rules.js';
import { RULE_CASES } from '../fixtures/rule-cases.mjs';

const root = path.resolve(import.meta.dirname, '..');
const catalog = new Map(RULE_CATALOG.map((r) => [r.id, r]));

async function run(files, binaries = {}) {
  const dir = mkdtempSync(path.join(tmpdir(), 'rs-ex-'));
  for (const [rel, content] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    writeFileSync(path.join(dir, rel), content);
  }
  for (const [rel, size] of Object.entries(binaries)) writeFileSync(path.join(dir, rel), Buffer.alloc(size));
  const res = await runAudit(dir);
  rmSync(dir, { recursive: true, force: true });
  return res;
}

const fence = (files) =>
  Object.entries(files)
    .map(([name, body]) => `\`\`\`${name.endsWith('.css') ? 'css' : name.endsWith('.tsx') ? 'tsx' : 'html'}\n/* ${name} */\n${body.trim().replace(/\n{2,}/g, '\n')}\n\`\`\``)
    .join('\n');

const out = [];
out.push('# Rule examples: failing and passing inputs', '');
out.push('Every example below is generated by running the real audit on the input shown (`npm run examples`). The same inputs are asserted in `test/rules.test.mjs`, so these pages cannot drift from the tested behaviour. HTML examples sit inside a minimal valid document so that other rules stay quiet.', '');
out.push('> **Note:** "Passing" means this rule did not fire on the input. It does not mean the input is accessible or well designed.', '');
let n = 0;
for (const c of RULE_CASES) {
  n++;
  const meta = catalog.get(c.rule);
  const bad = await run(c.bad, c.badBinary);
  const good = await run(c.good, c.goodBinary);
  const hit = bad.findings.find((f) => f.rule === c.rule);
  const goodHits = good.findings.filter((f) => f.rule === c.rule).length;
  out.push(`## ${c.rule}${c.name ? ` (${c.name})` : ''}: ${meta.title}`, '');
  out.push(`Category: ${meta.category}. Default severity: ${meta.severity}.${meta.criterion ? ` Criterion: ${meta.criterion}.` : ''}`, '');
  out.push('**Failing input**', '', c.bad && Object.keys(c.bad).length ? fence(c.badBinary ? { ...c.bad, [Object.keys(c.badBinary)[0]]: `(binary file, ${Object.values(c.badBinary)[0]} bytes)` } : c.bad) : '', '');
  out.push(`**Result:** \`${hit.id}\` [${hit.severity}/${hit.status}] ${hit.title} at \`${hit.file}${hit.line ? `:${hit.line}` : ''}\``, '');
  out.push('**Passing input**', '', fence(c.goodBinary ? { ...c.good, [Object.keys(c.goodBinary)[0]]: `(binary file, ${Object.values(c.goodBinary)[0]} bytes)` } : c.good), '');
  out.push(`**Result:** ${goodHits === 0 ? 'rule did not fire' : `UNEXPECTED: ${goodHits} hit(s)`}`, '');
}
out.push('## Guards against false positives', '', 'These inputs look suspicious but are correct. The rule must stay silent.', '');
const { FALSE_POSITIVE_GUARDS } = await import('../fixtures/rule-cases.mjs');
for (const g of FALSE_POSITIVE_GUARDS) {
  const res = await run(g.files);
  const fired = res.findings.filter((f) => f.rule === g.rule).length;
  out.push(`- \`${g.rule}\`: ${g.name}. Result: ${fired === 0 ? 'silent (correct)' : `UNEXPECTED ${fired} hit(s)`}`);
}
out.push('');
writeFileSync(path.join(root, 'documents', 'rachnasutra', '15-rule-examples.md'), out.join('\n'));
console.log(`wrote ${n} cases`);
